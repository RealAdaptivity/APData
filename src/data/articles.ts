export const ARTICLE_BY_SLUG: ReadonlyMap<string, Article> = new Map(ARTICLES.map((a) => [a.slug, a]));

export function searchArticles(query: string): Article[] {
  const words = query
    .toLowerCase()
    .split(/\s+/)
    .filter((w) => w.length > 1);
  if (!words.length) return [];
  return ARTICLES.map((a) => {
    const title = a.title.toLowerCase();
    const body = `${a.summary} ${a.useWhen.join(' ')} ${(a.codes ?? []).join(' ')} ${a.steps.map((s) => s.title).join(' ')}`.toLowerCase();
    let score = 0;
    for (const w of words) {
      if (title.includes(w)) score += 3;
      else if (body.includes(w)) score += 1;
      else return { a, score: 0 };
    }
    return { a, score };
  })
    .filter((x) => x.score > 0)
    .sort((x, y) => y.score - x.score)
    .map((x) => x.a);
}
